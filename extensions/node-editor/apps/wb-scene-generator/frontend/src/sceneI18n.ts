/** Studio interface persists locale here — stay in sync, never guess from navigator. */
export const STUDIO_LOCALE_KEY = 'forgeax.locale'

let registered = false

function readStudioLocale(): Locale {
  if (typeof window === 'undefined') return 'en'
  try {
    const raw = window.localStorage.getItem(STUDIO_LOCALE_KEY)
    if (raw === 'zh' || raw === 'en') return raw
    if (raw?.toLowerCase().startsWith('zh')) return 'zh'
  } catch {
    /* private mode */
  }
  return 'en'
}

function syncLocaleFromStudio(): void {
  setLocale(readStudioLocale())
}

export function ensureSceneI18n(): void {
  if (!registered) {
    registered = true
    registerCatalog('en', 'scene', EN)
    registerCatalog('zh', 'scene', ZH)
  }
  syncLocaleFromStudio()
}

export function useSceneLocale(): Locale {
  ensureSceneI18n()
  const [locale, setLocaleState] = useState(getLocale)
  useEffect(() => {
    const unsub = onLocaleChange(setLocaleState)
    const onStorage = (e: StorageEvent) => {
      if (!e.key || e.key === STUDIO_LOCALE_KEY) syncLocaleFromStudio()
    }
    window.addEventListener('storage', onStorage)
    return () => {
      unsub()
      window.removeEventListener('storage', onStorage)
    }
  }, [])
  return locale
}

export type SceneKey = keyof typeof EN

export function sceneT(key: SceneKey, vars?: Record<string, string | number>): string {
  ensureSceneI18n()
  return t(`scene.${key}`, vars)
}

export function sceneLoadingTaskLabel(id: 'previews' | 'baked' | 'aliases'): string {
  const key = `loading.task.${id}` as const
  return sceneT(key)
}
