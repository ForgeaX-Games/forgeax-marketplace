/**
 * 结构席逐层展开时的三条原则。
 *
 * 内容沿用老提示词里那组「命运必然论 / 有限突变论 / 双维度嵌套展开」——判断本身是对的，
 * 换掉的只是说法：那套命名与 L0/L1/L2 三层脚手架绑死，而新架构里只有「叙事单元 →
 * 剧情树节点」两级，层数由体量决定。这段此前在两个结构 step 里各抄了两遍，
 * 四份措辞已经开始漂移，合成一处。
 */
export function expansionPrinciples(opts: {
  /** 上游那一层的称呼，如「宏观框架」。 */
  upstream: string;
  /** 本层的称呼，如「大纲层」。 */
  here: string;
  /** 本层新分岔的收束义务。 */
  convergence: string;
}): string {
  return `## 展开原则
- **结局由上游锁定**：${opts.upstream}已经定下全部命运分支与结局，${opts.here}只在这个框架内细化，不新增结局。
- **允许局部突变**：${opts.here}可以自己长出新的分岔，但${opts.convergence}。
- **两个方向同时展开**：顺序方向把上游的一个节点拆成若干连续子节点；可能性方向在这些子节点之间开出分岔。`;
}

/**
 * 结构席：分支与主线的纪律。
 *
 * 只收「代码推不出、必须模型自律」的条款。功能位、出边走向、代价档的推导已由
 * outline-tree.deriveTreeFields 承担，不在这里重复要求。
 */
export const TOPOLOGY_DISCIPLINE = `## 分支纪律

**选项对等与唯一性**：同一处分岔的各选项必须两两语义互斥，不许用近义改写凑数
（「谨慎应对」与「小心行事」是同一个选项）。各选项的去向也必须两两不同：几条
不同的选项直连同一个普通节点或同一个聚合节点，是**假分支**——玩家按了不同的
按钮看到一样的剧情，这是体验事故。真需要殊途同归时，各选项先各自走到自己的
专属后果节点，演完差异再汇回。

**每处分岔都要有代价**：一组选项应当是同一个价值冲突的不同回答。判据是问
「这两条路想保住的是不是同一样东西」——若两边都只为查明真相、都只为救同一个人，
只是手段不同，那它只是策略分叉，不是选择。这时改写其中一条，让它去保护另一样
会被牺牲的东西（安全、信任、关系、原则、时间、名声）；改不出来就取消这处分岔，
改成顺流推进，不要留一个「选了也不用付代价」的选择。

**选项的前提必须已经建立**：一条选项所依赖的人物与关系，必须在更早的节点已经
出场并演过。让玩家去「帮一个他还不认识的人」，在情感上是站不住的；缺前提就先
补一个建立关系的节点，再放这处分岔。

## 最优路径判定

最优路径 = 最贴合用户需求的那一条从入口到结局的完整通路，判据依次是：
1. 终点优先取圆满结局（H）；多个圆满时取信息量最完整、情感曲线最满的那个；
2. 经过的关键节点最多，玩家走它能完整体验作品想表达的核心；
3. 分岔处偏向「主动 / 探索 / 共情」那一支。

入口节点必在最优路径上；最优路径本身是一条不分叉的链，直通它的结局。
被放弃的支线上的节点不在最优路径上，即便它们自己是顺流推进的。`;

/**
 * 情节席：正文写法与质量条款。
 *
 * 这几条是外部提示词里最贵的部分——每一条都对应一类具体的失败写法。
 */
export const PROSE_CRAFT = `## 正文写法

**画面与台词交替**：不允许整段纯描写，也不允许整段纯对白。描写只写镜头拍得到的
具象——动作、环境、光线、表情、道具、走位；判据是「这句话能不能被摄影机直接拍
下来」。抽象叙述（「他的人生从此改变」）、上帝视角旁白（「谁也没想到」）、以及
气味触感温度痛感这类非视听感官，都要改写成可见的等价物：机油味改成袖口那片黑亮
的油渍；冷改成呵出的白气与缩起的肩膀；痛改成攥紧的手与渗血的纱布。角色的隐藏
身份、职业、心理状态同理，靠动作、道具、台词外化，不在描写里直接断言。
内心独白控制在全节点对话行的 30% 以内，且每段独白要有相邻画面配对。

**每句台词都要有交付物**：每一句对白至少满足其一——给出新信息 / 施加压力或提出
要求 / 暴露说话人的立场与性格 / 直接推动一个动作发生。自检：把这句删掉，玩家会
不会少知道一件事、或少感受到一次压力？都不会就删掉。**严禁复述玩家已经看到的
信息**；确实要提起旧事时，必须带上新的态度、新的解读或新的要求。

**台词要有各自的口吻**：按角色档案的性格、身份、教养给每个有台词的角色定一条
自己的说话规矩（句子长短、用词层级、口头习惯、爱不爱把话说完），全篇保持一致。
自测办法是遮住角色名盲读，十句里至少七句能认出说话人；认不出，多半是所有人都在
说同一种标准书面语。

**主角不靠提问推进**：主角的疑问句不超过其台词的四分之一，且不允许连续两句都在问。
该说的是他的判断、他的要求、他的拒绝，而不是把问题抛回给对方。需要引出信息时，
让主角先给出判断逼对方回应（「你昨晚不在场，那把钥匙是你给的。」），或提出具体
要求与交换条件，或干脆让对方主动说、主角用一个动作回应。

## 按功能位分写

**分岔节点**按「现状 → 抛出问题 → 选项是回答」三段写：先用画面与台词把当下处境
与困境讲清楚，玩家凭这一段就该明白此刻的处境；再单独成行抛出那个问题；最后列出
选项——选项是对那个问题的回答，短标题是答案的浓缩，动作描述只写玩家自己的动作、
话或姿态。**严禁剧透**选择之后对方的反应、剧情走向与客观结果（那是后果节点要演
的），三类剧透词尤其要避开：对方人物名加动词、时间词加后续（「随即」「于是」）、
结论性形容词（「成功」「失败」「被认可」）。每条选项各自都要让玩家读出「这么做
我会失去什么、冒什么风险」；某条读起来毫无代价、明显是「更聪明的那个」，就给它
补上它自己要付的代价。

**聚合节点**演殊途同归：只写所有来路都成立的共同事实，**严禁条件式叙述**
（「如果你之前选了 A……选了 B 则……」），也不许让对白或情绪基调按来路变化。
汇合本身不是内容——这个节点还要自带一件新东西（新出现的人、新情报、新的时间
压力、因为汇合才产生的新麻烦），不能把两条路都已知道的事再说一遍就接回主干。

**结局节点**必须正面回应核心冲突：解决、妥协、失败或代价性达成都可以，但要明确
交代。**严禁「主角仓皇逃离 / 话题岔开 / 戛然而止」式把主线矛盾晾在一边**。正文
要演完「最后的关键事件 → 直接且不可逆的后果 → 对核心冲突的回应」。中途的失败
结局同样要给完整释放：它可以短，但至少演出这个选择的直接后果与情感落点再收，
不能只用一句旁白宣布主角失败了。

## 质量条款

**承载锚**：动笔前先定这个节点扛哪一项实质职责——推进了哪步剧情 / 关系长了哪步 /
埋或回扣哪条线索 / 抖了谁的底牌 / 设或收哪个抉择。正文要把职责**演出来**（具体
动作加具体台词），**严禁只写结果标签**（「自此追随」「成功脱困」「下定决心」）；
改法是把标签拆成看得见的一拍：一个具体动作加一句台词或内心。

**信息密度**：不写原地踏步的节点——只复述上一节的结果、只重复同一种情绪、只做
地点转移交代的内容，与相邻节点合并。最容易空转的是聚合节点与选项后果节点，它们
不豁免这一条。反过来也要控制负荷：一个节点新引入的命名实体（新角色、新线索、
新地点）超过三四个就该拆开或延后揭示，别把身份反转、旧案补叙、新角色登场堆在
相邻节点里。

**释放节奏**：不要让玩家一路挨打、把所有释放都攒到高潮。前三分之一就该有一处
让玩家舒一口气的时刻——主角小胜、扳回一局、反制成功、悬念被畅快揭开都算，可以
很小（一句反将、一个被戳破的谎、一件失物到手），但要让玩家看到主角的处境因此
好了一点。

**翻转要有前置伏笔**：作为翻转、揭密或身份反转的节点，必须能找到更早埋下的伏笔，
并完整演出「伏笔形成预期 → 真相揭示 → 关系或目标或行动随之改变」。没有前置伏笔、
或揭示后没有任何行动变化的，就是普通的信息揭露，不要当翻转写。

**配角要有自己的动机**：凡是有名有台词的角色，都要能让人看出他自己想要什么，并且
至少有一个节点里他为自己的目标主动做了一件事、逼得别人（包括主角）不得不回应。
只回答主角提问、只递线索、只帮忙的角色不算。某个角色实在没有自己的目标，就别给
他名字和独立戏份，并进别的角色或降成无名功能角色（「值班护士」「同事」）。

**给过戏份的东西要用掉**：特意给了描写的道具、被起了名字的角色，后面都要再出现
一次并影响某个动作、选择或真相。只出场一次、拿掉也不影响任何情节的，就不要给它
名字和特写，用无名的环境元素带过。

**时间跳跃要显式交代**：相邻节点之间只要跨天以上、跨年、跨人生阶段，该节点开头
必须有一句交代跨了多久、这段空白里变了什么（「三年后。他的书桌换了一张，窗外那棵
梧桐已经高过二楼」）。`;

/**
 * 分镜席：镜头语言。
 *
 * 只留镜头调度这一层——外部提示词里与之混写的生图/生视频字段规格属于对方的
 * 素材管线，我们的画面提示由美术侧消费，不在此处规定字数与字段。
 */
export const CAMERA_LANGUAGE = `## 镜头语言

按戏的性质选镜头序列，不要全篇一个机位：
- **进场**：远景 → 全景 → 中景，先交代环境与人物关系，再落到人；
- **对话**：中景 → 近景正反打，随情绪升温收紧景别；
- **心理**：近景 → 特写，用局部（手、眼、道具）承载说不出口的部分；
- **高潮**：全景 → 近景 → 特写，先给对撞的全局，再逼到脸上，最后钉在决定性细节。

一个镜头只承载一次画面切换及该画面下的声音与对白。镜头要能拍：写清景别、机位
运动与画面内的动作，不写「表现他内心的挣扎」这种拍不出来的意图。

**潜台词优先**：人物很少直说自己要什么。重要的台词都应带潜台词，把真意交给动作、
停顿与镜头去说；表演提示落在情感转折处，给演出留可执行的落点。`;
